def clean(s):
    import html as _h
    s = _h.unescape(re.sub(r"<[^>]+>", "", s or "")); s = s.replace(" ", " ").replace(" ", " ")
    return re.sub(r"\s+", " ", s).strip()

def entry(w, lang):
    i = 0 if lang == "ru" else 1
    rt = B.ROW_TEXT[lang].get(w["id"])
    title = B.card_title(w, lang) if (w["id"] in B.CARD_PAGE or w["level"] in ("constituent", "mention_in_corpus")) else (clean(B.md_inline(rt[0], lang)) if rt else (w.get("title") or ""))
    title = B.label_of(w["id"], lang) or B.lang_safe(clean(title), lang) or B.LINK_TEXT[lang].get(w["id"]) or (w.get("urls") or {}).get("primary", w["id"])
    u = (w.get("urls") or {}).get("primary")
    who = B.sup_pass(w, lang).get("orgs") or (B.PASS.get(w["id"], {}).get("orgs_en") if lang == "en" else B.PASS_RU.get(w["id"], {}).get("institutions_short")) or (clean(B.md_inline(rt[1], lang)) if rt else ", ".join(w.get("orgs") or []))
    date = (w.get("corpus") or {}).get("month") or w.get("date_first_public") or ""
    c = w.get("corpus") or {}
    st = c.get("source_type") if c.get("source_type") in B.STYPE else B.KIND2STYPE.get(w["kind"], "other")
    typ = B.STYPE[st][i]
    summ = clean(B.md_inline(B.LEADS[lang].get(w["id"]) or (rt[2] if rt else ""), lang))
    pg, anc = B.work_anchor(w["id"])
    chs = f" ({TXT[lang]['ch']} {int(pg[2:])})" if pg and pg.startswith("ch") else ""
    head = f"[{title}]({u})" if u else title
    meta = " · ".join(x for x in [B.lang_safe(clean(who), lang)[:90], date[:7], typ] if x)
    line = f"- {head}{chs} — {meta}."
    if summ: line += f" {summ}"
    ch_ = B.catalogue.changed(w["id"])
    if ch_ == "added":
        line = line.replace(" — ", f" — **{B.UI[lang]['added_tag']}** · ", 1)
    elif ch_:
        up = w["updates"][-1]
        line += f" **{B.sup_pass(w, lang).get('note', '')}** [{up['url']}]({up['url']})"
    elif w.get("updates"):
        up = w["updates"][-1]
        line += f" **{TXT[lang]['update']} {up['date']}:** " + (up["what"] if lang == "en" else B.ru_update(w["id"], up)) + f" [{up.get('doi') or up['url']}]({up['url']})"
    code = (w.get("urls") or {}).get("code")
    return line, code

def catalog(lang):
    T = TXT[lang]; st = B.STATS
    out = [f"# {T['title']}", "", T["intro"], "", f"**{T['counts']}:** " + T["n_line"].format(corpus=st.get("corpus"), full=st.get("cards_full"), short=st.get("cards_short"),
           rows=st.get("related_rows"), uniq=st.get("unique_works"), cat=st.get("catalogue"), sup=st.get("supplement_added"))
           + " · " + T["n_field"].format(all=len(B.WORKS) + len(F.additions()), pts=len(F.map_rows(lang))), ""]
    out += [f"## {T['start']}", "", T["start_note"], ""]
    for wid in START:
        if wid in B.WORKS: out.append(entry(B.WORKS[wid], lang)[0])
    out.append("")
    groups, other, codes = defaultdict(list), [], []
    for w in B.WORKS.values():
        pg, _ = B.work_anchor(w["id"])
        if not pg:
            pg = next((p for p in (w.get("source_pages") or []) if p.startswith("ch")), None)
        line, code = entry(w, lang)
        if code: codes.append((w, code))
        if w["kind"] == "dataset" and not (w.get("corpus") or {}): continue
        if w["level"] == "inline_link" and w["kind"] in ("news", "web", "lab_blog") and not pg: other.append(line); continue
        groups[pg or "other"].append((w, line))
    for p in B.PAGE_ORDER:
        if p not in groups: continue
        r = B.read_page(lang, p); title = r[0].get("title", p) if r else p
        num = r[0].get("num") if r else ""
        out += [f"## {num}. {title}" if num else f"## {title}", ""]
        for w, line in sorted(groups[p], key=lambda x: ((x[0].get("corpus") or {}).get("month") or x[0].get("date_first_public") or ""), reverse=True):
            out.append(line)
        out.append("")
    adds = F.additions(); rules = F.read_json("updates", "2026-11-12", "map-catalogue.json")["map"]
    themes = F.read_json("field", f"{lang}.json")["labels"]["themes"]
    out += [f"## {T['field']}", "", T["field_note"].format(n=len(adds), pts=len(F.map_rows(lang)), base=len(B.WORKS), merged=len(rules["merged"])), ""]
    for r in sorted(adds, key=lambda r: r["date_first_public"], reverse=True):
        typ = B.STYPE[B.KIND2STYPE.get(r["kind"], "other")][0 if lang == "ru" else 1]
        meta = " · ".join(x for x in [F.addition_who(r, lang), r["date_first_public"], typ, f"{T['theme']}: {themes[int(r['theme'][2:]) - 2]}"] if x)
        line = f"- [{r['title']}]({r['urls']['primary']}) — {meta}."
        if "Withdrawn" in (r.get("date_note") or ""):
            line += f" **{T['withdrawn']}**"
        out.append(line)
    out.append("")
    if codes:
        out += [f"## {T['code']}", ""]
        for w, code in codes:
            note = (w.get("urls") or {}).get("code_note")
            if note and lang == "ru":
                note = {"listed in the paper; returned HTTP 404 at the October check": "указан в статье; при октябрьской проверке HTTP 404",
                        "link taken from the paper, not opened at the October check": "ссылка из статьи, при октябрьской проверке не открывалась"}.get(note, note)
            out.append(f"- [{code}]({code}) — {clean(B.card_title(w, lang))}" + (f" ({note})" if note else ""))
        for w in B.WORKS.values():
            if w["kind"] == "dataset" and (w.get("urls") or {}).get("primary") and not (w.get("corpus") or {}):
                u = w["urls"]["primary"]; out.append(f"- [{u}]({u}) — " + (B.label_of(w["id"], lang) or B.LINK_TEXT[lang].get(w["id"]) or w["id"]))
        out.append("")
    if groups.get("other") or other:
        out += [f"## {T['other']}", ""] + [l for _, l in groups.get("other", [])] + other + [""]
    out += ["---", "", f"*{T['gen']}*", ""]
    return "\n".join(out)

def rights():
    figs = B.jload("data/figures.json", {"figures": []})["figures"]
    lab = {"cc-by-4.0": "CC BY 4.0", "cc-by-nc-nd-4.0": "CC BY-NC-ND 4.0", "arxiv-nonexclusive": "arXiv non-exclusive licence (not CC); attributed quotation",
           "all-rights-reserved": "© rights holder; attributed quotation", "own-cc-by-4.0": "survey's own chart, CC BY 4.0", "own-chart-cc0-data": "survey's own chart (CC BY 4.0) from CC0 repository data"}
    rows = ["| # | File | Page | Source work | Rights | Credit (as printed) |", "|---|---|---|---|---|---|"]
    for n, f in enumerate(figs, 1):
        rows.append(f"| {n} | `{f['file']}` | {f['page']} | {f.get('work_id') or '—'} | {lab.get(f['rights'], f['rights'])} | {clean(B.md_inline(f.get('credit_ru') or '', 'ru'))} |")
    from collections import Counter
    c = Counter(f["rights"] for f in figs)
    summ = ", ".join(f"{lab.get(k, k)}: {v}" for k, v in c.most_common())
    return f"""# Rights

| What | Licence |
|---|---|
| Survey text, tables, cards and metadata written for this survey (`content/`, `data/`) | [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/) — see `LICENSE-CONTENT.md` |
| Build and check scripts (`scripts/`), site CSS/JS (`assets/css`, `assets/js`) | MIT — see `LICENSE` |
| The survey's own charts (`assets/charts/`, `assets/figures/anthropic-c-compiler_fig2.png`) | CC BY 4.0 |
| Figures reproduced from the works (`assets/figures/`) | **Their owners' rights.** Not covered by the survey's licences. |

## Third-party figures

The October 2026 candidate keeps all 52 figures used in the text. Their rights were recorded per figure from each work's licence page and are printed under every figure on the site. Nothing here grants a licence that the owner did not.
Summary: {summ}.

Figures marked “attributed quotation” (© or arXiv non-exclusive) are reproduced for review and criticism with source and rights holder named. **Before any public release this list needs an explicit rights decision** (keep as quotation, request permission, or replace with a link or a redrawn chart).

{chr(10).join(rows)}

*Generated by `scripts/build_catalog.py` from `data/figures.json`.*
"""

