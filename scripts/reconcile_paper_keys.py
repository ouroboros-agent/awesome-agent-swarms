#!/usr/bin/env python3
"""Reconcile data/ IDs with the integrated paper's citation keys (paper/citation-key-map.json, read-only).

  python scripts/reconcile_paper_keys.py <path-to-paper-dir>

Writes `paper_reconciliation` into data/registry_overrides.json; scripts/build_registry.py applies it:
  * renames: a registry record whose normalized URL matches a paper key with a different name takes the
    paper key; the provisional registry ID is kept in `aliases` (October alias names go back to their bundle);
  * components: paper-only component documents of a card are added with `part_of` and claim their URL keys;
  * cards keep their card IDs (the paper also uses card filename stems for ordinary works).
"""
import hashlib, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from build_registry import key
P = sys.argv[1]
import subprocess
subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "build_registry.py")] + sys.argv[2:3], check=True, capture_output=True,
               env={**os.environ, "AAS_NO_RECONCILE": "1"})   # match against the registry WITHOUT a previous reconciliation
mp = os.path.join(P, "citation-key-map.json")
pm = json.load(open(mp, encoding="utf-8"))
reg = json.load(open(os.path.join(ROOT, "data/works.json"), encoding="utf-8"))
OCT_ALIASES = set(pm.get("corpus_aliases") or {})
k2 = {}
for w in reg["works"]:
    for k in w.get("identity_keys") or []: k2[k] = w["id"]
for u, wid in reg["text_url_map"].items(): k2.setdefault(key(u), wid)
ids = {w["id"]: w for w in reg["works"]}
renames, components = {}, []
for pk, e in pm["entries"].items():
    if pk in ids: continue
    mine = k2.get(key(e.get("url") or ""))
    w = ids.get(mine) if mine else None
    is_card = bool(w and w.get("level") in ("full_card", "short_card", "mention_in_corpus") and w.get("card_file"))
    if mine and not is_card and mine not in renames:
        renames[mine] = pk
    else:   # a component of a card (or a paper-only document): its own record, part_of the card
        components.append({"id": pk, "part_of": e.get("part_of") if (e.get("part_of") in ids or (mine and is_card)) else e.get("part_of"),
                           "card": mine if is_card else None, "title": e.get("title"), "url": e.get("url"),
                           "first_public": e.get("first_public"), "license": e.get("license"), "inherited_status": e.get("inherited_status")})
o = json.load(open(os.path.join(ROOT, "data/registry_overrides.json"), encoding="utf-8"))
o["paper_reconciliation"] = {
    "_note": "Generated by scripts/reconcile_paper_keys.py from the integrated paper's citation-key-map.json (read-only). Paper keys become canonical IDs; provisional registry IDs stay as aliases. October alias names stay attached to their bundle cards, as in the paper.",
    "source": "paper/citation-key-map.json", "source_sha256": hashlib.sha256(open(mp, "rb").read()).hexdigest(),
    "october_aliases_to_bundles": {a: t for a, t in (pm.get("corpus_aliases") or {}).items()},
    "renames": renames, "components": components,
    "part_of": {pk: e["part_of"] for pk, e in pm["entries"].items() if e.get("part_of")},
    "nonpublication_bundles": pm.get("nonpublication_bundles") or {}}
json.dump(o, open(os.path.join(ROOT, "data/registry_overrides.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print("renames", len(renames), "components", len(components))
for a, b in renames.items(): print(f"  {a} -> {b}")
for c in components: print(f"  + {c['id']} (part_of {c['part_of']}; card {c['card']})")
